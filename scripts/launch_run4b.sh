#!/usr/bin/env bash
# Provision a fresh pod, gate on a smoke, and launch a run-4 arm detached.
#
#   scripts/launch_run4b.sh <POD_IP> <POD_PORT> <4a|4b> [MODE]
#     MODE: --preflight-only | --assert-only | --smoke-only  (default: full launch)
#     --assert-only stops after stage 2: everything verified, nothing spent on a smoke.
#
# Stage order is deliberate: everything that can fail cheaply fails BEFORE the long run.
#   -1 preflight   : ssh + GPU + every real path, in one pass (§4e.5)
#    0 provision   : rsync + tmux installed AND verified with command -v
#    1 sync        : repo up
#    2 assert      : data files present; seed adapter present and HASH-matched (§4e.6)
#    3 smoke       : 20 steps with the real config; a pass is the go-signal
#    4 launch      : detached in tmux, tee'd, marker emitted from a correctly
#                    captured PIPESTATUS (§4e.1)
#
# WANDB: never handled here, and no key is ever read, printed, or written by this script.
# Set FDV_INJECT_CMD to an executable of your own taking <HOST> <PORT> <TMUX_SESSION>;
# stage 3 invokes it after creating the pane and before starting the smoke, so the key
# reaches the smoke's environment without passing through argv, disk, or this script.
# If FDV_INJECT_CMD is unset the step is skipped and the smoke runs without reporting.
#
# bash 3.2 clean (§4e.3). No `timeout` (§4e.2). stderr never suppressed on a
# verification step (§4e.4).
set -uo pipefail

usage() { echo "usage: $0 <POD_IP> <POD_PORT> <4a|4b> [--marker-test|--preflight-only|--assert-only|--smoke-only|--no-smoke]" >&2; exit 2; }
[ $# -ge 3 ] || usage
POD_IP="$1"; POD_PORT="$2"; ARM="$3"; MODE="${4:-}"

REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || { echo "not a git repo" >&2; exit 2; }
cd "$REPO_ROOT" || exit 2
. scripts/run4_paths.sh "$ARM" || exit 2

# Environment-specific default; override with FDV_SSH_KEY. Nothing here assumes this
# particular key exists — it is only the fallback used by the reference environment.
SSH_KEY="${FDV_SSH_KEY:-$HOME/.ssh/id_ed25519}"
SSH_OPTS="-p ${POD_PORT} -i ${SSH_KEY} -o StrictHostKeyChecking=accept-new"
REMOTE="root@${POD_IP}"

remote_sh() {
  if [ -n "${FDV_REMOTE_SH:-}" ]; then "$FDV_REMOTE_SH" "$1"; else ssh $SSH_OPTS "$REMOTE" "$1"; fi
}
# Write a runner SCRIPT to the pod and start it under tmux.
#
# Why a script and not `tmux send-keys "long command"`: send-keys re-parses the string
# through another shell layer, and the nested escaping silently ate $RC on the first
# 4b smoke — the pane printed "SMOKE_RC=" with an empty value. §4e.1 in both directions:
# a marker that cannot report success is as broken as one that cannot report failure.
# Inside a real script there is exactly one level of quoting, and PIPESTATUS is captured
# on the line immediately after the pipeline with nothing between.
#
#   run_in_tmux <session> <remote_script> <logfile> <marker_ok> <marker_bad> <command>
run_in_tmux() {
  _sess="$1"; _rs="$2"; _log="$3"; _ok="$4"; _bad="$5"; _cmd="$6"
  _tmp=$(mktemp) || return 1
  cat > "$_tmp" <<RUNNER
#!/bin/bash
# GENERATED by scripts/launch_run4b.sh — do not hand-edit on the pod.
set -uo pipefail
cd '${REMOTE_REPO}' || exit 2
source /workspace/env.sh
${_cmd} 2>&1 | tee '${_log}'
RC=\${PIPESTATUS[0]}
if [ "\$RC" -eq 0 ]; then echo '${_ok}' | tee -a '${_log}'; else echo '${_bad}' "rc=\$RC" | tee -a '${_log}'; fi
echo "EXIT_RC=\$RC" | tee -a '${_log}'
RUNNER
  if [ -n "${FDV_REMOTE_SH:-}" ]; then
    cp "$_tmp" "$_rs"
  else
    scp -P "${POD_PORT}" -i "${SSH_KEY}" -o StrictHostKeyChecking=accept-new \
        "$_tmp" "root@${POD_IP}:${_rs}" >/dev/null
  fi
  _scp_rc=$?
  rm -f "$_tmp"
  [ "$_scp_rc" -eq 0 ] || return 1
  remote_sh "chmod +x '${_rs}'; tmux kill-session -t '${_sess}' >/dev/null 2>&1; tmux new-session -d -s '${_sess}' bash '${_rs}'; sleep 2; tmux list-sessions"
}

fail() { echo ""; echo "FAILED: $*" >&2; exit 1; }
say()  { echo ""; echo "=== $* ==="; }

# ── --marker-test: prove the marker mechanism reports SUCCESS as well as failure ──
# §4e.1 cost us in both directions: run-4a reported FAILED for a completed run, and the
# first 4b smoke reported an EMPTY rc. A marker that only ever reports failure correctly
# is half-tested, so this runs a trivially-succeeding command and a trivially-failing one
# through the exact same runner-script path the smoke and the launch use.
if [ "$MODE" = "--marker-test" ]; then
  say "marker test (both directions) through the real run_in_tmux path"
  MT_FAILED_ANY=0
  for _case in ok bad; do
    if [ "$_case" = "ok" ]; then _c="true"; _want="EXIT_RC=0"; _wantm="MT_COMPLETE"; else _c="false"; _want="EXIT_RC=1"; _wantm="MT_FAILED"; fi
    run_in_tmux "mt_${_case}" "/workspace/mt_${_case}.sh" "/workspace/mt_${_case}.log" \
                "MT_COMPLETE" "MT_FAILED" "$_c" >/dev/null
    _rc=$?
    [ "$_rc" -eq 0 ] || fail "run_in_tmux failed to start case '${_case}' (rc=${_rc})"
    sleep 3
    _out=$(remote_sh "cat /workspace/mt_${_case}.log 2>&1")
    echo "    case ${_case} (cmd '${_c}') log: $(printf '%s' "$_out" | tr '\n' ' ')"
    case "$_out" in
      *"$_want"*) echo "      rc marker  OK  (${_want})" ;;
      *) echo "      rc marker  WRONG — expected ${_want}"; MT_FAILED_ANY=1 ;;
    esac
    case "$_out" in
      *"$_wantm"*) echo "      completion OK  (${_wantm})" ;;
      *) echo "      completion WRONG — expected ${_wantm}"; MT_FAILED_ANY=1 ;;
    esac
  done
  remote_sh "rm -f /workspace/mt_ok.sh /workspace/mt_bad.sh /workspace/mt_ok.log /workspace/mt_bad.log" >/dev/null 2>&1
  [ "$MT_FAILED_ANY" -eq 0 ] || fail "marker mechanism is NOT trustworthy — do not launch"
  say "MARKER TEST PASSED — success and failure both reported correctly"
  exit 0
fi

# ── stage -1: preflight ─────────────────────────────────────────────────────────
say "stage -1  preflight (arm=${ARM}, run_name=${RUN_NAME})"
PRE=$(remote_sh "echo \"host \$(hostname)\"; nvidia-smi --query-gpu=name,memory.total,memory.used --format=csv,noheader 2>&1 | head -4; for p in '${REMOTE_REPO}' '${REMOTE_SEED_ADAPTER}'; do if [ -e \"\$p\" ]; then echo \"OK   \$p\"; else echo \"MISS \$p\"; fi; done")
PRE_RC=$?
echo "$PRE" | sed 's/^/    /'
[ "$PRE_RC" -eq 0 ] || fail "cannot reach the pod (rc=${PRE_RC})"

# ── stage 0: provision ─────────────────────────────────────────────────────────
# ENVIRONMENT-SPECIFIC: apt-get and the missing rsync/tmux are properties of the
# Debian-based `runpod/pytorch:*` container this run used, not universal setup. On any
# other image, replace the install line; the `command -v` verification below is the part
# that generalises — never accept an install step's exit status as proof.
say "stage 0   provision rsync + tmux, then VERIFY"
remote_sh "command -v rsync >/dev/null 2>&1 && command -v tmux >/dev/null 2>&1 || { apt-get update -qq && apt-get install -y -qq rsync tmux; }; echo '--- verify ---'; for t in rsync tmux; do if command -v \$t >/dev/null 2>&1; then echo \"OK   \$t \$(command -v \$t)\"; else echo \"MISS \$t\"; fi; done" > /tmp/fdv_prov.txt 2>&1
PROV_RC=$?
cat /tmp/fdv_prov.txt | sed 's/^/    /'
[ "$PROV_RC" -eq 0 ] || fail "provisioning returned rc=${PROV_RC}"
grep -q '^MISS ' /tmp/fdv_prov.txt && fail "rsync or tmux still missing after install — a hopeful echo is not a check"

if [ "$MODE" = "--preflight-only" ]; then say "PREFLIGHT ONLY — stopping"; exit 0; fi

# ── stage 1: sync the repo up ───────────────────────────────────────────────────
say "stage 1   rsync repo -> ${REMOTE_REPO}"
if [ -n "${FDV_REMOTE_SH:-}" ]; then
  echo "    [test seam] FDV_REMOTE_SH set — skipping real rsync"
  SYNC_RC=0
else
  rsync -rltvP --no-owner --no-group \
    --exclude '.venv' --exclude '.git' --exclude '__pycache__' \
    --exclude 'wandb/' --exclude 'data/checkpoints/' --exclude 'data/*.log' \
    -e "ssh ${SSH_OPTS}" ./ "${REMOTE}:${REMOTE_REPO}/"
  SYNC_RC=$?
fi
[ "$SYNC_RC" -eq 0 ] || fail "rsync up returned rc=${SYNC_RC}"

# ── stage 2: assert data + seed adapter, by hash not by listing (§4e.6) ─────────
say "stage 2   assert data files and seed adapter"
DATA_CHK=$(remote_sh "cd '${REMOTE_REPO}' && for f in ${REQUIRED_DATA}; do if [ -s \"\$f\" ]; then echo \"OK   \$f\"; else echo \"MISS \$f\"; fi; done")
echo "$DATA_CHK" | sed 's/^/    /'
printf '%s\n' "$DATA_CHK" | grep -q '^MISS ' && fail "required data file missing on the pod"

LOCAL_SEED="data/checkpoints/sft_v3_balanced_nodecoy/sft_B_seed42/checkpoint-1296/adapter_model.safetensors"
if [ -f "$LOCAL_SEED" ]; then
  LH=$(shasum -a 256 "$LOCAL_SEED" | awk '{print $1}')
  RH=$(remote_sh "sha256sum '${REMOTE_SEED_ADAPTER}/adapter_model.safetensors' | cut -d' ' -f1")
  echo "    seed adapter local : ${LH}"
  echo "    seed adapter pod   : ${RH}"
  [ "$LH" = "$RH" ] || fail "seed adapter differs between local and pod — training from the wrong weights would invalidate the arm (§4e.6)"
  echo "    seed adapter MATCHES"
else
  echo "    note: local seed adapter absent, cannot cross-hash (pod copy asserted present above)"
fi

# ── stage 2b: the venv must be 4a's stack, or refuse ────────────────────────────
# Checked through `source /workspace/env.sh`, i.e. the interpreter the runner scripts
# will actually use — not a hardcoded path. 4b's first smoke died because env.sh still
# pointed at a corrupted venv; that failure cost ~20 minutes inside a smoke and would
# have cost 12.4 hours inside the real run.
say "stage 2b  venv must match run-4a's pins"
FREEZE=$(remote_sh "source /workspace/env.sh; echo \"PYTHON=\$(which python)\"; pip freeze 2>/dev/null")
FREEZE_RC=$?
[ "$FREEZE_RC" -eq 0 ] || fail "could not read pip freeze on the pod (rc=${FREEZE_RC})"
echo "    $(printf '%s\n' "$FREEZE" | grep '^PYTHON=' | sed 's/^/interpreter /')"
PIN_BAD=0
for _pin in $FDV_REQUIRED_PINS; do
  _name=${_pin%%==*}
  _want=${_pin#*==}
  _got=$(printf '%s\n' "$FREEZE" | grep -iE "^${_name}==" | head -1 | cut -d= -f3-)
  if [ "$_got" = "$_want" ]; then
    printf "    %-14s %-16s OK\n" "$_name" "$_want"
  else
    printf "    %-14s want %-16s got %-16s DIFFERS\n" "$_name" "$_want" "${_got:-ABSENT}"
    PIN_BAD=1
  fi
done
[ "$PIN_BAD" -eq 0 ] || fail "pod venv does not match run-4a's stack — refusing to launch. \
4b must run the same stack as 4a or the arms differ by more than the one reward constant."
echo "    all $(echo $FDV_REQUIRED_PINS | wc -w | tr -d ' ') pins match run-4a"

# ── stage 2c: the RESOLVED config must be the specified 4b config, or refuse ────
# Asserted against `train_grpo.py --print-config`, which applies every override in the
# same order a real run does and REBUILDS the val instrument. This is the check that
# would have caught run 4b's first smoke: --max-steps re-overrode smoke_overrides and the
# val instrument silently became n=32 while the argument string still looked correct.
say "stage 2c  resolved config must equal the specified 4b config"
CFG_RAW=$(remote_sh "cd '${REMOTE_REPO}' && source /workspace/env.sh && python grpo/train_grpo.py ${TRAIN_ARGS} --print-config 2>&1")
CFG_RC=$?
[ "$CFG_RC" -eq 0 ] || { echo "$CFG_RAW" | tail -20 | sed 's/^/    /'; fail "--print-config failed (rc=${CFG_RC})"; }
CFG_JSON=$(printf '%s\n' "$CFG_RAW" | sed -n '/PRINT_CONFIG_JSON_BEGIN/,/PRINT_CONFIG_JSON_END/p' | sed '1d;$d')
[ -n "$CFG_JSON" ] || { echo "$CFG_RAW" | tail -20 | sed 's/^/    /'; fail "could not extract the resolved-config JSON"; }

printf '%s\n' "$CFG_JSON" > /tmp/fdv_resolved_config.json
python3 - "$EXPECTED_MAX_STEPS" "$EXPECTED_SAVE_STEPS" "$EXPECTED_EVAL_EVERY" \
          "$EXPECTED_POOL_ABSTAIN" "$EXPECTED_POOL_ANSWERABLE" "$EXPECTED_TEMPERATURE" \
          "$EXPECTED_TOP_P" "$EXPECTED_NUM_GENERATIONS" "$EXPECTED_FALSE_ABSTAIN_BASE" \
          "$EXPECTED_SMOKE" "$EXPECTED_INSTRUMENT_N" "$EXPECTED_INSTRUMENT_ABSTAIN" \
          "$EXPECTED_INSTRUMENT_ANSWERABLE" "$EXPECTED_INSTRUMENT_SHA" \
          "$EXPECTED_ADAPTER_SUFFIX" <<'PYCHK'
import json, sys
(ms, ss, ee, pa, pq, temp, topp, ng, fab, smoke, iN, iA, iQ, ish, adap) = sys.argv[1:16]
d = json.load(open("/tmp/fdv_resolved_config.json"))
c, v = d["resolved_config"], d["val_instrument"]
checks = [
    ("max_steps",            c["max_steps"],            int(ms)),
    ("save_steps",           c["save_steps"],           int(ss)),
    ("eval_every",           c["eval_every"],           int(ee)),
    ("pool_abstain",         c["pool_abstain"],         int(pa)),
    ("pool_answerable",      c["pool_answerable"],      int(pq)),
    ("temperature",          float(c["temperature"]),   float(temp)),
    ("top_p",                float(c["top_p"]),         float(topp)),
    ("num_generations",      c["num_generations"],      int(ng)),
    ("false_abstain_base",   float(c["false_abstain_base"]), float(fab)),
    ("smoke",                bool(c["smoke"]),          smoke == "true"),
    ("val_recurs_false_only", bool(c["val_recurs_false_only"]), True),
    ("instrument n",         v["n"],                    int(iN)),
    ("instrument abstain",   v["n_abstain"],            int(iA)),
    ("instrument answerable", v["n_answerable"],        int(iQ)),
    ("instrument ids sha256", v["record_ids_sha256"],   ish),
]
bad = 0
for name, got, want in checks:
    ok = got == want
    bad += 0 if ok else 1
    shown_g = str(got)[:16] + "..." if len(str(got)) > 20 else got
    shown_w = str(want)[:16] + "..." if len(str(want)) > 20 else want
    print(f"    {name:<24} {str(shown_g):<20} expected {str(shown_w):<20} {'OK' if ok else 'MISMATCH'}")
if not str(c["adapter"]).rstrip("/").endswith(adap):
    print(f"    {'seed adapter':<24} {c['adapter']:<20} expected *{adap:<19} MISMATCH"); bad += 1
else:
    print(f"    {'seed adapter':<24} ...{adap:<17} expected *{adap:<19} OK")
print(f"    -> {len(checks)+1} assertions, {bad} mismatch(es)")
sys.exit(1 if bad else 0)
PYCHK
CHK_RC=$?
[ "$CHK_RC" -eq 0 ] || fail "resolved config is NOT the specified 4b config — refusing to launch"
echo "    resolved config matches the specified 4b config"

if [ "$MODE" = "--assert-only" ]; then say "ASSERT ONLY — everything verified, nothing spent"; exit 0; fi

# ── stage 3: smoke — the go-signal (skippable) ─────────────────────────────────
# --no-smoke: run every assertion (stages -1..2c) then launch, skipping the smoke.
# Used for 4b after the smoke was replaced by the stage-2c resolved-config assertion:
# the failure that mattered was argument construction, which a smoke does not test,
# and 4.5h of the misconfigured run already retired the OOM/stack questions.
if [ "$MODE" = "--no-smoke" ]; then
  say "stage 3   SKIPPED (--no-smoke) — assertions in 2/2b/2c stand in for it"
else


# Runs INSIDE tmux, because a key-injection hook of this shape pastes into a tmux pane; a
# plain `ssh host "python ..."` would never see it. Same tmux pattern as stage 4.
say "stage 3   smoke (20 steps, real config)"
# SMOKE_ARGS comes from scripts/run4_paths.sh — do NOT rebuild it from TRAIN_ARGS here.
# An earlier version of this script did exactly that, which re-overrode the smoke shrink
# (max_steps 20 -> 150, pool 40/60 -> 1764/2646) and produced a 150-step "smoke".
# --wandb is appended here because reporting is a launcher concern and applies to the
# SMOKE ONLY: both arms' long runs ran on jsonl telemetry (see the analysis plan's
# 2026-08-17 amendment, which records §(d)'s W&B line as unmet for 4a and 4b alike).
SMOKE_ARGS="${SMOKE_ARGS} --wandb"
SMOKE_SESSION="${TMUX_SESSION}_smoke"
SMOKE_LOG="/workspace/smoke_${FDV_ARM}.log"
echo "    session : ${SMOKE_SESSION}"
echo "    log     : ${SMOKE_LOG}"
echo "    args    : ${SMOKE_ARGS}"

# create the session via the runner helper AFTER key injection, so the pane the key
# lands in is the same pane the smoke runs in.
remote_sh "tmux kill-session -t '${SMOKE_SESSION}' >/dev/null 2>&1; tmux new-session -d -s '${SMOKE_SESSION}' bash -l; sleep 1; tmux list-sessions"
SESS_RC=$?
[ "$SESS_RC" -eq 0 ] || fail "could not create tmux session (rc=${SESS_RC})"

if [ -n "${FDV_INJECT_CMD:-}" ]; then
  echo "    injecting W&B key via ${FDV_INJECT_CMD} (value never shown)"
  "$FDV_INJECT_CMD" "$POD_IP" "$POD_PORT" "$SMOKE_SESSION"
  INJ_RC=$?
  [ "$INJ_RC" -eq 0 ] || fail "W&B key injection failed (rc=${INJ_RC})"
fi

# The runner script inherits the pane's env (incl. the injected key) because we start it
# with send-keys INTO that pane — one token, no nested command string.
SMOKE_RUNNER="/workspace/run_smoke_${FDV_ARM}.sh"
_tmp=$(mktemp)
cat > "$_tmp" <<RUNNER
#!/bin/bash
# GENERATED by scripts/launch_run4b.sh — do not hand-edit on the pod.
set -uo pipefail
cd '${REMOTE_REPO}' || exit 2
source /workspace/env.sh
python grpo/train_grpo.py ${SMOKE_ARGS} 2>&1 | tee '${SMOKE_LOG}'
RC=\${PIPESTATUS[0]}
if [ "\$RC" -eq 0 ]; then echo 'SMOKE4B_COMPLETE'; else echo 'SMOKE4B_FAILED' "rc=\$RC"; fi
echo "SMOKE_RC=\$RC" | tee -a '${SMOKE_LOG}'
RUNNER
scp -P "${POD_PORT}" -i "${SSH_KEY}" -o StrictHostKeyChecking=accept-new "$_tmp" "root@${POD_IP}:${SMOKE_RUNNER}" >/dev/null
SCP_RC=$?; rm -f "$_tmp"
[ "$SCP_RC" -eq 0 ] || fail "could not upload smoke runner (rc=${SCP_RC})"
remote_sh "chmod +x '${SMOKE_RUNNER}'; tmux send-keys -t '${SMOKE_SESSION}' 'bash ${SMOKE_RUNNER}' Enter; sleep 2; tmux list-sessions"
SEND_RC=$?
[ "$SEND_RC" -eq 0 ] || fail "could not start smoke in tmux (rc=${SEND_RC})"
echo "    smoke started in tmux; poll ${SMOKE_LOG} for the W&B URL and SMOKE_RC"

if [ "$MODE" = "--smoke-only" ]; then say "SMOKE ONLY — stopping before the long run"; exit 0; fi

fi   # end --no-smoke guard

# ── stage 4: launch detached, with a marker that tells the truth (§4e.1) ────────
say "stage 4   launch ${RUN_NAME} detached in tmux session '${TMUX_SESSION}'"
# Same runner-script mechanism as the smoke. run-4a emitted JOB4A_FAILED for a run that
# completed because PIPESTATUS was read inside $( ); the first 4b smoke then lost $RC to
# send-keys re-parsing. Both failure modes come from re-parsing a command string through
# an extra shell layer — a real script on disk has exactly one.
LAUNCH_RUNNER="/workspace/run_${FDV_ARM}.sh"
run_in_tmux "${TMUX_SESSION}" "${LAUNCH_RUNNER}" "${REMOTE_LOG}" \
            "${MARKER_OK}" "${MARKER_BAD}" \
            "python grpo/train_grpo.py ${TRAIN_ARGS}"
LAUNCH_RC=$?
[ "$LAUNCH_RC" -eq 0 ] || fail "tmux launch returned rc=${LAUNCH_RC}"

cat <<EOF

=== LAUNCHED ===
  session : ${TMUX_SESSION}
  log     : ${REMOTE_LOG}
  run dir : ${REMOTE_RUN_DIR}
  marker  : ${MARKER_OK} on success, ${MARKER_BAD} on failure

  Inject W&B, if you use it (key never touches argv, disk, or this script):
    FDV_INJECT_CMD=<your-hook> ; \$FDV_INJECT_CMD ${POD_IP} ${POD_PORT} ${TMUX_SESSION}

  Watch (attach from your LOCAL terminal, never from inside the session):
    ssh ${SSH_OPTS} ${REMOTE} -t 'tmux attach -t ${TMUX_SESSION}'
    detach with: tmux detach   (never 'exit' — that kills the session)

  When the marker appears, pull and PROVE it arrived:
    scripts/run4_pull_verify.sh ${POD_IP} ${POD_PORT} ${ARM}

  Only after that verifies: stop the pod. 4a idled ~6.6h (~\$10.7) on a bad marker.
EOF
